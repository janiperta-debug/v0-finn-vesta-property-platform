/**
 * Creates the saved_reports table in Supabase.
 * Run once: node --env-file-if-exists=/vercel/share/.env.project scripts/setup-saved-reports.mjs
 *
 * Requires SUPABASE_DB_URL or will derive a connection string from
 * NEXT_PUBLIC_SUPABASE_URL + the project password (not stored here).
 *
 * If SUPABASE_DB_URL is not available, falls back to the Supabase Management API
 * using SUPABASE_SERVICE_ROLE_KEY.
 */
import { createClient } from "../node_modules/.pnpm/@supabase+supabase-js@2.104.1/node_modules/@supabase/supabase-js/dist/module/index.js"

const url = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim()
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY?.trim()
const anonKey = (process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY)?.trim()

if (!url) {
  console.error("NEXT_PUBLIC_SUPABASE_URL not set")
  process.exit(1)
}

// Use service role key if available for DDL, otherwise anon (will likely fail DDL).
const key = serviceKey || anonKey
if (!key) {
  console.error("No Supabase key found")
  process.exit(1)
}

const supabase = createClient(url, key, { auth: { persistSession: false } })

const DDL = `
-- saved_reports: stores metadata for every report generated by a user.
create table if not exists public.saved_reports (
  id            uuid primary key default gen_random_uuid(),
  report_id     text not null unique,          -- human-readable: FVR-2026-000001
  org_id        int4 not null references public.organizations(id) on delete cascade,
  created_by    text not null,                 -- auth.uid()
  title         text not null,
  property_names text[] not null default '{}', -- display names of buildings
  building_ids  int4[] not null default '{}',  -- FK refs to buildings.id
  report_type   text not null default 'custom',
  language      text not null default 'fi',
  version       int4 not null default 1,
  status        text not null default 'generated' check (status in ('draft','generated','archived')),
  config        jsonb not null,                -- full ReportConfig for viewer/duplicate
  generated_at  timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

-- Sequence for the numeric part of report_id (per org would need a different approach,
-- a global sequence is fine for now).
create sequence if not exists public.saved_reports_seq;

-- RLS
alter table public.saved_reports enable row level security;

create policy if not exists "saved_reports_select_own_org"
  on public.saved_reports for select
  using (
    org_id in (
      select org_id from public.org_users where user_id = auth.uid()
    )
  );

create policy if not exists "saved_reports_insert_own"
  on public.saved_reports for insert
  with check (created_by = auth.uid()::text);

create policy if not exists "saved_reports_update_own"
  on public.saved_reports for update
  using (created_by = auth.uid()::text);

create policy if not exists "saved_reports_delete_own"
  on public.saved_reports for delete
  using (created_by = auth.uid()::text);

-- Helper function to generate the next human-readable report ID.
create or replace function public.next_report_id()
returns text
language sql
security definer
set search_path = ''
as $$
  select 'FVR-' || extract(year from now())::text || '-' ||
         lpad(nextval('public.saved_reports_seq')::text, 6, '0')
$$;
`

const { error } = await supabase.rpc("exec_sql", { sql: DDL }).single()

if (error) {
  // exec_sql RPC may not exist; try direct REST
  console.error("exec_sql RPC failed:", error.message)
  console.log("If running with service role key, try psql or the Supabase SQL editor instead.")
  console.log("SQL to run manually:\n")
  console.log(DDL)
  process.exit(1)
}

console.log("saved_reports table and policies created successfully.")
